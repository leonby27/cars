// Частые вопросы в карточке машины.
//
// Зачем: вопросы и ответы уже стоят на разделах каталога, обзорах моделей, страницах
// расчётов и в журнале — не было их только на карточках, то есть на самых массовых
// страницах сайта. А спрашивают про конкретную машину ровно то же, что и вообще:
// «сколько выйдет под ключ», «что на таможне», «сколько ждать», «что проверяют».
//
// Главное условие — ответы считаются по этой машине, а не переписываются с шаблона.
// Одинаковый блок на десятках тысяч страниц поисковик читает как штамповку, и
// пересказывающему нас чат-боту он тоже ничего не даёт. Поэтому в каждом ответе
// стоят числа именно этой карточки: итог до Минска, разбивка платежей, возраст,
// пробег, ёмкость батареи. Совпасть у двух машин может разве что вопрос про сроки —
// он один на всех и по смыслу, и по ответу.
//
// Тот же набор показывают приложение и страница для поисковика (вместе с разметкой
// FAQPage), поэтому файл лежит в общем коде, а не в одном из них.
import { isEvQuotaExhausted } from "./ev-quota.js";

const RU = new Intl.NumberFormat("ru-RU");
const number = (value) => RU.format(Math.round(Number(value) || 0));
const money = (value) => (Number.isFinite(Number(value)) ? `${number(value)} $` : null);

const plural = (value, one, few, many) => {
  const abs = Math.abs(Math.round(Number(value) || 0)) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last > 1 && last < 5) return few;
  return last === 1 ? one : many;
};

const title = (car) => [car?.brand, car?.model, car?.year].filter(Boolean).join(" ") || "эта машина";

/** Из чего складывается итог: те же этапы, что и в разбивке под ценой. */
function priceAnswer(car, landed) {
  const total = money(landed?.totalUsd);
  if (!total) return null;
  const parts = [
    landed.chinaUsd ? `${money(landed.chinaUsd)} — цена продавца в Китае` : null,
    landed.customsUsd ? `${money(landed.customsUsd)} — таможенные платежи и сборы` : null,
    landed.intlHigh ? `около ${money((Number(landed.intlLow) + Number(landed.intlHigh)) / 2)} — доставка до Беларуси` : null,
    landed.serviceUsd ? `около ${money(landed.serviceUsd)} — подбор и сопровождение` : null,
  ].filter(Boolean);
  return {
    q: `Сколько будет стоить ${title(car)} с доставкой в Минск?`,
    a: `Ориентировочно ${total} под ключ${parts.length ? `: ${parts.join("; ")}` : ""}. Сумма предварительная: перед договором цену у продавца, курс и стоимость перевозки подтверждают заново, поэтому итог может немного сдвинуться. Полная разбивка по этапам — в расчёте под ценой на этой странице.`,
  };
}

/** Что именно платится на таможне за эту машину — по её типу двигателя и возрасту. */
function dutyAnswer(car, landed) {
  const age = Number(landed?.ageYears);
  const overFive = Number.isFinite(age) && age > 5;
  const customs = money(landed?.customsUsd);
  const tail = customs ? ` В этой карточке всё вместе — ${customs}, и в итоговую сумму оно уже заложено.` : "";
  const q = `Какие платежи на таможне у ${title(car)}?`;
  if (car?.type === "Электромобиль") {
    const quota = isEvQuotaExhausted()
      ? "Квота на льготный ввоз электромобилей 2026 года выбрана, поэтому начисляется пошлина 15% от таможенной стоимости."
      : "Пока действует квота на льготный ввоз, пошлины у электромобиля нет — только оформление и сборы.";
    const vat = overFive
      ? ` Машине больше пяти лет с даты выпуска, поэтому сверху идёт НДС 20%: нулевую ставку дают только машинам моложе пяти лет.`
      : ` Машине меньше пяти лет с даты выпуска, поэтому НДС при ввозе нулевой.`;
    return { q, a: `${quota}${vat}${tail}` };
  }
  if (landed?.seriesHybrid) {
    return {
      q,
      a: `Это последовательный гибрид: колёса крутит только электромотор, а бензиновый работает генератором. С 2026 года такие машины оформляют по ставке 15% от стоимости плюс НДС 20% сверху — льгота на них не распространяется.${tail}`,
    };
  }
  if (car?.type === "Гибрид") {
    return {
      q,
      a: `У гибрида с розеткой бензиновый мотор может крутить колёса сам, поэтому таможня считает его как обычную машину: пошлина по объёму двигателя и возрасту, а не процентом от цены.${tail}`,
    };
  }
  const byAge = overFive
    ? "машине больше пяти лет, поэтому ставка выше — от 3 до 5,7 евро за кубический сантиметр по возрастанию объёма"
    : Number.isFinite(age) && age <= 3
      ? "машине не больше трёх лет, поэтому пошлину берут процентом от стоимости"
      : "машине от трёх до пяти лет, поэтому ставка — от 1,5 до 3,6 евро за кубический сантиметр по возрастанию объёма";
  return {
    q,
    a: `Пошлину на бензиновую машину считают не от цены, а по объёму двигателя и возрасту: ${byAge}. Сверху утилизационный сбор и сборы за оформление.${tail}`,
  };
}

/** Что проверяют именно у этой машины: пробег, возраст, батарея. */
function checkAnswer(car, landed) {
  const bits = [];
  if (car?.mileage) bits.push(`пробег ${number(car.mileage)} ${plural(car.mileage, "километр", "километра", "километров")} сверяют с записями о ремонтах и страховых случаях`);
  if (car?.battery) bits.push(`у батареи на ${number(car.battery)} кВт·ч замеряют остаточную ёмкость`);
  if (Number.isFinite(Number(landed?.ageYears))) bits.push(`возраст — ${number(landed.ageYears)} ${plural(landed.ageYears, "год", "года", "лет")}, а от него зависит и ставка на таможне, и состояние расходников`);
  if (car?.owners) bits.push(`по документам у машины ${plural(car.owners, "был", "было", "было")} ${number(car.owners)} ${plural(car.owners, "владелец", "владельца", "владельцев")}`);
  if (!bits.length) return null;
  return {
    q: `Что проверяют у ${title(car)} перед покупкой?`,
    a: `Перед покупкой машину осматривают на площадке: ${bits.join("; ")}. По итогам приходит отчёт с фотографиями и замерами — до оплаты, а не после.`,
  };
}

const DELIVERY = {
  q: "Сколько ждать машину из Китая?",
  a: "Обычно 30–50 дней от договора до Минска: выкуп у продавца, экспортные документы, доставка до границы, таможенное оформление и путь до Минска. Срок зависит от города отправления, перевозчика и очереди на границе; статус сообщают на каждом этапе.",
};

/**
 * Вопросы и ответы для карточки машины.
 *
 * `landed` — результат estimateLandedCost для этой же машины: числа берём оттуда, а не
 * считаем заново, иначе ответ разошёлся бы с ценой на той же странице. Проданной
 * машине блок не нужен — её страница живёт только ради прямых ссылок.
 *
 * Возвращает массив `{ q, a }` — тот же вид, что у разделов каталога и обзоров.
 */
export function carFaq(car, landed) {
  if (!car || car.available === false || !landed) return [];
  return [priceAnswer(car, landed), dutyAnswer(car, landed), DELIVERY, checkAnswer(car, landed)].filter(Boolean);
}

/** Заголовок блока — с названием машины, чтобы он не был одинаковым на всех карточках. */
export const carFaqTitle = (car) => `Частые вопросы: ${title(car)} из Китая`;
