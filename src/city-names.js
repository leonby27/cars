/** Русское название города или null, если его в справочнике нет. */
export const cityName = (value) => {
  const raw = String(value ?? "").trim();
  if (!raw) return null;
  return CITY_NAMES[raw] || CITY_NAMES[raw.toLowerCase()] || CITY_NAMES[raw.toLowerCase().replace(/[_\s-]/g, "")] || null;
};
