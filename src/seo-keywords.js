export function normalizeSeoQuery(value) {
  return String(value || "").normalize("NFKC").trim().toLocaleLowerCase("ru-RU").replaceAll("ё", "е").replace(/\s+/g, " ");
}

function queryIndex(source) {
  return new Map((source?.queries || []).map((row) => [normalizeSeoQuery(row.value), row]));
}

export function buildSeoPositionRows(report) {
  const yandex = queryIndex(report?.yandex);
  const google = queryIndex(report?.google);
  return SEO_POSITION_CORE.map((keyword) => ({
    ...keyword,
    yandex:yandex.get(normalizeSeoQuery(keyword.query)) || null,
    google:google.get(normalizeSeoQuery(keyword.query)) || null,
  }));
}
