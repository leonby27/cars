/**
 * Резервный статический каталог содержит только машины в продаже. Поэтому отсутствие
 * карточки в нём ничего не говорит о её настоящем состоянии: проданная машина может
 * ещё находиться в двухнедельном окне избранного. Удалять сохранённый номер можно
 * только после 404 от основного API, который знает `sold_at` и срок хранения.
 */
export const missingFavoriteIsExpired = (apiMode, status) => apiMode === true && status === 404;
