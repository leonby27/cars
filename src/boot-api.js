// Ответы API, встроенные в готовую страницу: window.__boot.api = { "<адрес>": ответ }.
//
// Страницы, которые собираются заранее (журнал, инструменты, справочные), рисует то же
// приложение, что и в браузере (scripts/prerender-pages.mjs). Блоки с живыми данными —
// подборки машин, сводки сравнений, справочник марок — сами ходят в API после первого
// кадра. Чтобы готовая страница несла эти данные, а браузер нарисовал первый кадр из
// тех же байт, блок сначала спрашивает этот словарь: ответ есть — рисует из него, а
// свежий запрос уходит уже после оживления.
//
// Сборка узнаёт, какие адреса нужны странице, из самой отрисовки: первый проход
// записывает каждый спрошенный адрес (window.__bootRecord), сборка получает ответы из
// базы, второй проход рисует страницу уже с ними.

/** Встроенный ответ по адресу или undefined. */
export function embeddedApiValue(url) {
  if (!url) return undefined;
  const scope = globalThis.window;
  const map = scope?.__boot?.api;
  if (map && Object.prototype.hasOwnProperty.call(map, url)) return map[url];
  if (typeof scope?.__bootRecord === "function") scope.__bootRecord(url);
  return undefined;
}
