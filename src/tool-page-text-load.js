// Подгрузка текстов страниц-инструментов (src/tool-page-texts.js) отдельным
// файлом — по образцу текстов обзоров моделей (src/model-text-load.js).
// Зачем: тексты нужны только на четырёх страницах, а лежали бы в общем файле
// приложения, который браузер качает на любой странице сайта.
//
// При заходе по прямой ссылке src/main.jsx дожидается этого файла до запуска
// приложения — тогда страница рисуется сразу с текстом, без скачка. При переходе
// внутри сайта тексты доезжают за долю секунды и страница дорисовывается.

let cache = null;
let promise = null;

/** Тексты, если они уже загружены, иначе null. */
export const loadedToolPageTexts = () => cache;

/** Загрузить тексты (повторные вызовы возвращают тот же запрос). */
export const loadToolPageTexts = () => {
  if (!promise) {
    promise = import("./tool-page-texts.js").then((module) => {
      cache = module.TOOL_PAGE_TEXTS;
      return cache;
    });
  }
  return promise;
};
