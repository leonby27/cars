import { CATALOG_LANDINGS, catalogLandingForFilters, catalogPlaceholderRedirect, landingFilterParams, modelLandingPath, parseModelLandingPath } from "./catalog-landings.js";
import { originFromParam } from "./origin.js";
import { isTrackingParam, withoutTrackingParams } from "./tracking-params.js";

export const CATALOG_SORTS = new Set(["default", "price_asc", "price_desc", "newest", "mileage_asc", "range_desc", "year_desc", "year_asc"]);
const BRAND_NAMES = new Map(CATALOG_LANDINGS.filter(landing => landing.kind === "brand").map(landing => [landing.brand.toLowerCase(), landing.brand]));
const MULTI = new Set(["model", "body", "color", "brandNot", "modelNot", "bodyTypeNot", "typeNot", "driveNot", "colorNot"]);

export const catalogShuffleSeed = (now = Date.now()) => `s${Math.floor((now + 3 * 3600 * 1000) / 86400000) % 12}`;

export const catalogSort = (params, model = false) => CATALOG_SORTS.has(params.get("sort"))
  ? params.get("sort") : params.get("page") || model ? "price_asc" : "default";

/** Path filters are defaults; explicit query values take precedence. */
export function catalogUrlParams(landing, search) {
  const params = new URLSearchParams(search);
  for (const [key, value] of landingFilterParams(landing)) if (!params.has(key)) params.append(key, value);
  return params;
}

/** A stable selection identity, independent of tracking and parameter order. */
export function catalogLocationKey(path, search) {
  const params = withoutTrackingParams(search);
  params.sort();
  const query = params.toString();
  return `${path}${query ? `?${query}` : ""}`;
}

/** Model first, otherwise the most specific existing section; every other condition stays in the query. */
export function catalogHref(search, { page, tracking = false } = {}) {
  let params = new URLSearchParams(search);
  const cleaned = catalogPlaceholderRedirect("/catalog", params);
  if (cleaned) params = new URLSearchParams(cleaned.split("?")[1]);
  for (const key of [...new Set(params.keys())]) {
    if (!tracking && isTrackingParam(key)) { params.delete(key); continue; }
    let values = params.getAll(key).map(value => value.trim()).filter(Boolean);
    if (MULTI.has(key)) values = [...new Set(values.flatMap(value => value.split(",")).map(value => value.trim()).filter(Boolean))].sort();
    if (key === "brand") values = values.map(value => BRAND_NAMES.get(value.toLowerCase()) || value);
    if (key === "country") values = values.map(value => originFromParam(value) || value);
    if (key === "type") values = values.map(value => ({ "Электромобиль": "Электромобили", "Гибрид": "Гибриды", "ДВС": "Бензин" })[value] || value);
    params.delete(key);
    for (const value of values) params.append(key, value);
  }
  if (page !== undefined) {
    params.delete("page");
    if (Number(page) > 1) params.set("page", String(page));
  } else if (params.get("page") === "1") params.delete("page");
  const model = params.getAll("brand").length === 1 && params.getAll("model").length === 1
    ? modelLandingPath(params.get("brand"), params.get("model")) : null;
  const landing = model ? { brand: params.get("brand"), model: params.get("model") } : catalogLandingForFilters(params);
  const path = model || landing?.path || "/catalog";
  for (const [key, value] of landingFilterParams(landing)) {
    if (params.getAll(key).length === 1 && params.get(key) === value) params.delete(key);
  }
  const defaultSort = params.has("page") || parseModelLandingPath(path) ? "price_asc" : "default";
  const selectedSort = params.get("sort") || defaultSort;
  if (selectedSort === defaultSort) params.delete("sort");
  if (selectedSort !== "default") params.delete("seed");
  params.sort();
  const query = params.toString();
  return `${path}${query ? `?${query}` : ""}`;
}

/** Normalize old/filtered entry URLs with the same rule as links generated by the UI. */
export function catalogRedirect(landing, search, path = landing?.path || "/catalog") {
  const target = catalogHref(catalogUrlParams(landing, search), { tracking: true });
  const url = new URL(target, "https://abcars.by");
  return catalogLocationKey(path, search) === catalogLocationKey(url.pathname, url.search) ? null : target;
}
