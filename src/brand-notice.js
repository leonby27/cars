// Предупреждение в карточке машины: то, что относится ко всей марке, а не к
// конкретному объявлению, и по чему посетитель может ошибиться в цене.
//
// Пока такой случай один — NIO. Марка строилась вокруг станций замены батареи,
// и часть машин продавалась по подписке: батарея принадлежит производителю, в
// цену объявления не входит и вывозу не подлежит. Если не сказать об этом до
// заказа, посетитель увидит рост цены уже после проверки машины.
const NOTICES = {
  NIO: {
    title: "Батарея может быть в аренде",
    lines: [
      "Не у каждой машины NIO батарея в собственности: бывает подписка, и тогда батарею выкупают отдельно — примерно 9–10 тысяч долларов.",
      "Станций замены батареи в Беларуси нет, но NIO заряжается от любой зарядки.",
    ],
  },
};

export function brandNotice(brand) {
  if (!brand) return null;
  return NOTICES[String(brand).trim().toUpperCase()] || null;
}
