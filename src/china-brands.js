// Зачем отдельная страница. «Значки китайских автомобилей», «названия китайских марок»
// и «как читается» — это около тысячи запросов в месяц только в Яндексе, и приходят с
// ними люди, которые китайскую машину ещё только рассматривают. Ни у одного конкурента
// такой страницы нет: у всех либо каталог, либо статья про одну марку.
//
// Откуда что берётся. Значки уже лежат в `public/brands` — те же файлы, что стоят на
