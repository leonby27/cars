// Справочник китайских марок: значок, как читается, кто владеет, чем известна.
//
// Зачем отдельная страница. «Значки китайских автомобилей», «названия китайских марок»
// и «как читается» — это около тысячи запросов в месяц только в Яндексе, и приходят с
// ними люди, которые китайскую машину ещё только рассматривают. Ни у одного конкурента
// такой страницы нет: у всех либо каталог, либо статья про одну марку.
//
// Откуда что берётся. Значки уже лежат в `public/brands` — те же файлы, что стоят на
// карточках и в разделах каталога; отдельных картинок для этой страницы не делаем.
// Число машин и ссылка в каталог берутся живыми из тех же данных, что и разделы: если
// марка кончилась, строка справочника это покажет, а не соврёт.
//
// Что здесь нарочно не написано. Ни слова про надёжность, ресурс и «что лучше брать»:
// проверенных данных по этим маркам у нас нет, а выдуманный рейтинг — ровно то, за что
// мы ругаем конкурентов. Только проверяемое: кто владеет маркой, когда появилась, какие
// машины делает.
//
// Произношение даём в том виде, в каком марку называют в Беларуси, а не в «правильном»
// китайском. Человек ищет «бид» и «джили», а не «бияди» и «цзили»; наша задача —
// чтобы он себя узнал.

