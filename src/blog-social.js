// Тексты материалов журнала для соцсетей.
//
// Статья в журнале — это несколько тысяч знаков, в ленте столько никто не читает.
// Поэтому у каждого материала здесь лежит своя выжимка: три-четыре строки, которые
// пересказывают суть и дают повод открыть полный текст. Пишется она один раз, вместе
// со статьёй, и дальше уходит в ленты сама — материалы журнала выходят по расписанию
// (поле `published` в src/blog-posts.js), и запись появляется в день выхода.
//
// Почему отдельным файлом, а не полем в blog-posts.js: там и так полторы тысячи строк,
// а эти тексты правятся отдельно от самих статей. Так же отделены тексты обзоров
// моделей (src/model-texts.js).
//
// Правила для выжимки:
//  - первая строка — заголовок материала, можно короче оригинального;
//  - дальше два абзаца: о чём речь и что человек узнает. Без «читайте в нашем блоге»;
//  - никаких цифр, которые устаревают быстрее статьи (остаток квоты, курс);
//  - ссылки в тексте не нужны: их подставляет механизм, и для Instagram он их убирает,
//    потому что там ссылки не кликаются.
//
// Если выжимки для вышедшего материала нет, запись не уходит: механизм сообщает об
// этом в телеграм, чтобы текст дописали.

