// Страницы каталога под марку, тип двигателя и тип кузова: `/catalog/byd`,
// `/catalog/electric`, `/catalog/suv`.
//
// Зачем: люди ищут «BYD из Китая», «электромобиль из Китая купить», «кроссовер из Китая
// цена» гораздо чаще, чем конкретное объявление. До этого на такие запросы у нас была
// одна общая страница каталога: ссылки на марки вели на адрес с параметром
// (`/catalog?brand=BYD`), а он указывает поисковику на общий каталог как на
// первоисточник — то есть отдельной страницы под марку не существовало вовсе.
//
// Своей вёрстки у этих страниц нет: показывается обычный каталог с заранее выставленным
// фильтром, а сверху — заголовок и короткий текст отсюда. Список моделей и количество
// машин берутся из каталога в момент показа, поэтому страница не устаревает.
//
// Поле `lead` у разделов больше не выводится: подзаголовок под заголовком дублировал
// слова из самого заголовка и из описания страницы для поиска, а количество и цена и так
// стоят рядом — в кнопке и над выдачей. Удалить его из всех записей стоит отдельной
// уборкой: сейчас этот файл правят в другой сессии.
// Текст намеренно короткий и только про проверяемое: чем марка отличается, из чего
// состоит её линейка и что важно знать при ввозе. Обещаний и оценок здесь нет.

