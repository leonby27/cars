// Подпись под заголовком одна на все разделы каталога. Раньше она собиралась из хвоста
// самой фразы, и от раздела к разделу менялась («доставка в Беларусь», «с доставкой
// в Беларусь», «купить с доставкой…»): при переходе между разделами строка дёргалась,
// хотя говорила одно и то же.
export const LANDING_SUBTITLE = "Купить с доставкой в Беларусь";

/**
 * Заголовок раздела для показа: длинную фразу из `h1` разбираем на две строки крупного
 * заголовка и одну мелкую подпись под ними. «Бензиновые автомобили с пробегом из Китая —
 * купить с доставкой в Беларусь» занимало на телефоне четыре строки во весь первый экран;
 * теперь это «Бензиновые автомобили» / «с пробегом из Китая» и подпись мелким шрифтом.
 *
 * Слова со страницы никуда не деваются — они те же и в том же порядке, просто набраны
 * разным размером: прятать часть заголовка только на телефоне нельзя, поисковик судит
 * страницу по её телефонному виду, и спрятанное считается отсутствующим.
 *
 * Служебный хвост отрезается по тире («… — доставка в Беларусь») или по «с доставкой»
 * там, где тире нет («Электрические кроссоверы из Китая с доставкой в Беларусь»), —
 * вместо него встаёт общая подпись. Вторая строка заголовка всегда начинается с «из
 * Китая» (или «с пробегом из Китая»), чтобы у всех разделов перенос стоял в одном месте.
 */
export const landingHeading = (h1) => {
  const text = String(h1 ?? "").trim();
  const dash = text.split(" — ");
  const title = dash.length > 1 ? dash[0] : splitByDelivery(text);
  const at = title.includes(FROM_CHINA_LONG) ? title.indexOf(FROM_CHINA_LONG) : title.indexOf(FROM_CHINA);
  return at > 0
    ? { title: title.slice(0, at).trim(), tail: title.slice(at).trim(), subtitle: LANDING_SUBTITLE }
    : { title, tail: "", subtitle: LANDING_SUBTITLE };
};

const FROM_CHINA_LONG = "с пробегом из Китая";
const FROM_CHINA = "из Китая";

const splitByDelivery = (text) => {
  const at = text.indexOf(" с доставкой ");
  return at > 0 ? text.slice(0, at) : text;
};

