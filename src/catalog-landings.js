/**
 * Разделы, на которые стоит ссылаться со страницы этого раздела.
 *
 * Раньше здесь стояли все 54 остальных, одним и тем же блоком на каждой странице: из
 * 138 ссылок на странице марки 68 повторялись на всех страницах. Поисковик такой
 * одинаковый блок со временем считает частью шаблона и обесценивает, а вес размазывается
 * ровным слоем — со страницы BYD ссылка на «Гибридные минивэны» получала столько же,
 * сколько ссылка на «Седаны BYD».
 *
 * Теперь сначала идут разделы, у которых с этим общие условия (та же марка, тот же
 * кузов, тот же тип двигателя), а остаток добирается по кругу от текущего места
 * в списке — так у каждой страницы набор соседей свой, а полный список всех разделов
 * лежит в одном месте, в каталоге.
 */
export const relatedLandings = (landing, { limit = 12 } = {}) => {
  if (!landing) return [];
  const index = CATALOG_LANDINGS.findIndex((item) => item.path === landing.path);
  const shared = (item) => {
    let points = 0;
    if (landing.brand && item.brand === landing.brand) points += 4;
    if (landing.bodyType && item.bodyType === landing.bodyType) points += 3;
    if (landing.powertrain && item.powertrain === landing.powertrain) points += 3;
    if (landing.landedMax && item.landedMax) points += 3;
    return points;
  };
  const picked = [];
  const seen = new Set([landing.path]);
  for (const item of CATALOG_LANDINGS.filter((row) => shared(row) > 0).sort((a, b) => shared(b) - shared(a))) {
    if (seen.has(item.path)) continue;
    seen.add(item.path);
    picked.push(item);
    if (picked.length >= limit) return picked;
  }
  // Добираем остальных по кругу с шагом 7. Шаг взаимно простой с длиной списка, поэтому
  // обход рано или поздно проходит по всем разделам, а соседние страницы (BYD и Tesla
  // стоят рядом) получают разные наборы — иначе у них снова совпадал бы почти весь блок.
  const stride = 7;
  for (let step = 1; step <= CATALOG_LANDINGS.length && picked.length < limit; step += 1) {
    const item = CATALOG_LANDINGS[(Math.max(0, index) + step * stride) % CATALOG_LANDINGS.length];
    if (seen.has(item.path)) continue;
    seen.add(item.path);
    picked.push(item);
  }
  return picked;
};

/**
 * Разделы, к которым относится машина: её марка, тип двигателя и тип кузова.
 * Нужны ссылкам с карточки: без них из карточки роботу некуда идти, кроме соседних
 * машин той же модели.
 */
export const landingsForCar = (car) => {
  if (!car) return [];
  return CATALOG_LANDINGS.filter((landing) => {
    // Совпасть должны все условия раздела, а не любое из них: у раздела
    // «электрические кроссоверы» их два, и по одному совпадению туда попал бы
    // и бензиновый кроссовер, и электрический седан.
    if (landing.brand && landing.brand !== car.brand) return false;
    if (landing.powertrain && landing.powertrain !== car.type) return false;
    if (landing.bodyType && landing.bodyType !== car.bodyType) return false;
    // Ценовые полосы пропускаем: итоговая цена считается отдельно, и тянуть расчёт
    // в этот справочник незачем.
    if (landing.landedMax) return false;
    return true;
  });
};

/**
 * Фильтры каталога, которые задаёт страница, — в том виде, в каком их читает каталог
 * из адреса. Благодаря этому страница марки остаётся обычным каталогом с выставленным
 * фильтром, а не отдельной вёрсткой.
 */
export const landingFilterParams = (landing) => {
  const params = new URLSearchParams();
  if (!landing) return params;
  if (landing.brand) params.set("brand", landing.brand);
  if (landing.powertrain) params.set("type", landing.filterLabel || landing.powertrain);
  if (landing.bodyType) params.set("body", landing.bodyType);
  // Верхняя граница цены — в долларах итоговой суммы до Минска, как её показывает
  // карточка и как её понимает фильтр каталога.
  if (landing.landedMax) params.set("priceTo", String(landing.landedMax));
  return params;
};

/**
 * Те же фильтры для запроса к каталогу. Отдельная функция потому, что кузов в адресе
 * страницы называется `body`, а в запросе к каталогу — `bodyType`; из-за этого
 * расхождения страница кузова молча показывала бы весь каталог.
 */
export const landingApiParams = (landing) => {
  const params = new URLSearchParams();
  if (!landing) return params;
  if (landing.brand) params.set("brand", landing.brand);
  if (landing.powertrain) params.set("type", landing.powertrain);
  if (landing.bodyType) params.set("bodyType", landing.bodyType);
  if (landing.landedMax) params.set("landedMax", String(landing.landedMax));
  return params;
};

// ── Адрес каталога с фильтрами ────────────────────────────────────────────────
// `/catalog?brand=BYD` показывает ровно то же, что `/catalog/byd`, но для поисковика
// это был отдельный адрес, у которого первоисточником значился общий каталог со всеми
// машинами. Ссылка на такой адрес отдавала вес не разделу марки, а каталогу; вдобавок
// поисковик вправе не поверить указанию, когда «первоисточник» на копию не похож, —
// и выбрать в выдачу адрес с параметрами вместо готовой страницы раздела.
// Поэтому сервер сверяет фильтры из адреса с разделами и, если они совпадают
// полностью, перебрасывает на раздел.

/**
 * Параметры адреса каталога, которые меняют состав выдачи. `sort` сюда не входит
 * намеренно: порядок показа выдачу не меняет, и такой адрес — та же подборка.
 */
const CATALOG_FILTER_KEYS = Object.freeze([
  "type", "brand", "model", "body", "color", "yearFrom", "yearTo", "year", "mileage",
  "priceFrom", "priceTo", "price", "drive", "owners", "battery", "condition",
  "accel", "tire", "torque", "range", "engine", "power", "gearbox", "fuel", "q",
  "brandNot", "modelNot", "bodyTypeNot", "typeNot", "driveNot", "colorNot",
]);

/**
 * Подписи выпадающих списков, означающие «не выбрано»: поиск на главной уносит
 * в адрес весь набор фильтров сразу, поэтому `/catalog?brand=BYD&type=Все&mileage=Пробег`
 * — это тоже просто BYD. Список повторяет константы `ANY_*` приложения; за тем,
 * чтобы он не отстал от них, следит тест.
 */
const ANY_FILTER_VALUES = new Set([
  "Все", "Все марки", "Все модели", "Все кузова", "Все цвета",
  "Год от", "До", "Цена от", "Пробег", "Состояние", "Владельцы", "Батарея",
  "Привод", "Разгон до", "Размер шин", "Крутящий момент", "Запас хода",
  "Объём двигателя", "Мощность", "Коробка", "Топливо",
]);
// «Крутящий момент» и ключ `torque` выше фильтром быть перестали (24.08.2026), но
// остались в списках: по сайту и в закладках живут старые ссылки с этим параметром,
// и адрес с ним по-прежнему нужно чистить, а не считать выбранным фильтром.

const asSearchParams = (search) => (search instanceof URLSearchParams ? search : new URLSearchParams(search || ""));

/** Выбранные фильтры из адреса: только те, у которых есть настоящее значение. */
const chosenFilters = (params) => {
  const chosen = new Map();
  for (const key of CATALOG_FILTER_KEYS) {
    const values = params.getAll(key).map((value) => String(value).trim()).filter((value) => value && !ANY_FILTER_VALUES.has(value));
    if (values.length) chosen.set(key, values);
  }
  return chosen;
};

/**
 * Раздел каталога, который в точности повторяет фильтры из адреса, или null.
 * Совпасть должен весь набор: `/catalog?brand=BYD&yearFrom=2023` — это уже не раздел
 * марки, а её часть, и своей страницы у неё нет.
 */
export const catalogLandingForParams = (search) => {
  const chosen = chosenFilters(asSearchParams(search));
  if (!chosen.size) return null;
  // Два значения одного фильтра («две марки сразу») ни одним разделом не описываются.
  if ([...chosen.values()].some((values) => values.length > 1)) return null;
  return (
    CATALOG_LANDINGS.find((landing) => {
      const wanted = [...landingFilterParams(landing)];
      return wanted.length === chosen.size && wanted.every(([key, value]) => String(chosen.get(key)?.[0] || "").toLowerCase() === String(value).toLowerCase());
    }) || null
  );
};

/**
 * Адрес раздела, на который нужно перебросить адрес каталога с фильтрами, или null,
 * если такого раздела нет. Всё, что не фильтр — метки рекламных кампаний, порядок
 * сортировки, — переносится в новый адрес: иначе переброс терял бы источник перехода
 * в статистике.
 */
export const catalogLandingRedirect = (search) => {
  const params = asSearchParams(search);
  const landing = catalogLandingForParams(params);
  if (!landing) return null;
  const kept = new URLSearchParams();
  for (const [key, value] of params) {
    if (CATALOG_FILTER_KEYS.includes(key) || !String(value).trim()) continue;
    kept.append(key, value);
  }
  const query = kept.toString();
  return `${landing.path}${query ? `?${query}` : ""}`;
};

/**
 * Тот же адрес без подписей «не выбрано» — или null, если чистить нечего.
 *
 * Поиск на главной когда-то уносил в адрес весь набор списков сразу, поэтому по сайту
 * и в закладках остались ссылки вида `/catalog?type=Все&mileage=Пробег&drive=Привод`:
 * длинная строка, которая ничего не фильтрует. Выдачу такие подписи не меняли — их
 * пропускает и сервер, и каталог, — но адрес у одной и той же страницы получался
 * разный, и отправить его человеку было нельзя. Теперь такой адрес перебрасывается
 * на чистый; всё остальное (метки переходов, страница списка, порядок) остаётся.
 */
export const catalogPlaceholderRedirect = (path, search) => {
  const params = asSearchParams(search);
  const kept = new URLSearchParams();
  let dropped = false;
  for (const [key, value] of params) {
    const trimmed = String(value).trim();
    if (CATALOG_FILTER_KEYS.includes(key) && (!trimmed || ANY_FILTER_VALUES.has(trimmed))) {
      dropped = true;
      continue;
    }
    kept.append(key, value);
  }
  if (!dropped) return null;
  const query = kept.toString();
  return `${path}${query ? `?${query}` : ""}`;
};

/**
 * Раздел, под которым уместно показывать выдачу с такими фильтрами, или null.
 * В отличие от переброса адреса (`catalogLandingForParams`) здесь допускаются лишние
 * фильтры: страница «Автомобили BYD» остаётся правдой и когда выбрана модель или год.
 * А вот выбрать на странице седанов ещё и кроссоверы — значит выйти за её пределы:
 * такие фильтры раздел уже не описывает, и заголовок начинает врать.
 *
 * `preferPath` — раздел, на котором посетитель уже стоит: если он не хуже найденного,
 * остаёмся на нём, чтобы страница не менялась без нужды.
 */
export const catalogLandingForFilters = (search, preferPath = null) => {
  const chosen = chosenFilters(asSearchParams(search));
  const single = (key) => (chosen.get(key)?.length === 1 ? chosen.get(key)[0] : null);
  const same = (left, right) => String(left || "").toLowerCase() === String(right).toLowerCase();
  const covers = (landing) => {
    const wanted = [...landingFilterParams(landing)];
    return wanted.length > 0 && wanted.every(([key, value]) => same(single(key), value));
  };
  const rank = (landing) => [...landingFilterParams(landing)].length;
  const fitting = CATALOG_LANDINGS.filter(covers);
  if (!fitting.length) return null;
  const best = Math.max(...fitting.map(rank));
  const top = fitting.filter((landing) => rank(landing) === best);
  return top.find((landing) => landing.path === preferPath) || top[0];
};
