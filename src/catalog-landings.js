// `/catalog?brand=BYD` показывает ровно то же, что `/catalog/byd`, но для поисковика
// это был отдельный адрес, у которого первоисточником значился общий каталог со всеми
// машинами. Ссылка на такой адрес отдавала вес не разделу марки, а каталогу; вдобавок
// поисковик вправе не поверить указанию, когда «первоисточник» на копию не похож, —
