const dutyAnswer = (entry) => {
  if (typeof entry.a === "string") return entry;
  const exhausted = isEvQuotaExhausted();
  const text = exhausted ? entry.a.over : entry.a.live;
  const date = evQuotaState({ audience: "personal" }).exhaustedOnLabel;
  return { q: entry.q, a: text.replace("{date}", date || "в сентябре 2026 года") };
};

