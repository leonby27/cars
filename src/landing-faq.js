// Пока квота есть — нулевая ставка и предупреждение, что она кончается; когда
// выбрана (у граждан это случилось 5 сентября 2026) — пошлина 15% и оговорка, что
// на 2027 год льготу могут открыть заново. Раньше здесь стояла одна фраза «пока
// действует квота — нулевая ставка, после неё 15%»: она верна формально, но после
// обнуления квоты читается как «льгота ещё работает», а это неправда.
