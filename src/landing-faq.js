// Четвёртый вопрос — про сам раздел: у марки это модели в наличии, у типа и кузова —
// как отобрать машину фильтрами, у ценовой полосы — что входит в сумму.
function aboutSection(landing) {
  if (landing.brand) {
    return {
      q: `Какие модели ${landing.brand} есть в наличии?`,
      a: `Список моделей раздела с количеством машин по каждой стоит в фильтре над выдачей — он собран из живого каталога и меняется вместе с ним. На самые массовые модели у нас есть отдельные обзоры: чем китайская версия отличается от привычной, какие моторы и батареи ставили по годам и на что смотреть при выборе. Ссылки на обзоры ${landing.brand} — под текстом раздела.`,
    };
  }
  if (landing.kind === "price") {
    const limit = landing.landedMax ? `${number(landing.landedMax)} $` : "указанной суммы";
    return {
      q: "Что входит в эту сумму?",
      a: `Полоса считается по итоговой цене до Минска, а не по цене в Китае: в раздел попадают только машины, которые под ключ выходят дешевле ${limit}. В сумму входят цена продавца, проверка, доставка, таможенные платежи и наши услуги — то есть машина из этого раздела не подорожает при оформлении вдвое. Итог в карточке предварительный: перед договором мы подтверждаем цену продавца, курс и логистику.`,
    };
  }
  const what = landing.name.toLowerCase();
  return {
    q: `Как выбрать ${what} в этом разделе?`,
    a: `Над выдачей стоят фильтры по марке и модели, году, пробегу, цене и характеристикам: у бензиновых машин это объём двигателя, мощность, коробка и привод, у электрических — ёмкость батареи и запас хода. Сортировка по цене выстраивает машины по итоговой сумме до Минска, поэтому сравнивать варианты можно сразу по деньгам, а не по цене продавца.`,
  };
}

/**
 * Вопросы и ответы для раздела каталога.
 *
 * `total` — сколько машин в разделе сейчас; без него первый вопрос пропускаем, чтобы
 * не сочинять число. Возвращает массив `{ q, a }` — тот же вид, что у обзоров моделей.
 */
export function landingFaq(landing, { total = null } = {}) {
  if (!landing) return [];
  const items = [];
  const count = Number(total);
  if (Number.isFinite(count) && count > 0) {
    items.push({
      q: `${subject(landing)} из Китая — сколько стоят с доставкой в Минск?`,
      a: `Сейчас в разделе ${number(count)} ${plural(count, "автомобиль", "автомобиля", "автомобилей")}, и у каждого в карточке стоит итоговая сумма до Минска: цена продавца, проверка перед покупкой, доставка, таможенные платежи и наши услуги. Сумма предварительная — перед договором мы подтверждаем цену у продавца, курс и стоимость логистики, а разбор по этапам показываем в самой карточке.`,
    });
  }
  const duty = powertrainOf(landing);
  items.push(duty && DUTY_ANSWERS[duty] ? DUTY_ANSWERS[duty] : DUTY_MIXED);
  items.push(DELIVERY);
  items.push(aboutSection(landing));
  return items;
}

