// Частые вопросы под списком раздела каталога: `/catalog/petrol`, `/catalog/haval`,
// `/catalog/audi-suv` и остальные сто с лишним страниц.
//
// Зачем: у разделов каталога был только короткий текст-врезка (два абзаца), а у обзоров
// моделей и страниц-расчётов вопросы есть давно — и именно вопросами люди формулируют
// запрос: «сколько стоит привезти», «какая пошлина», «сколько ждать». Ответы здесь
// короткие и только про проверяемое: числа берутся из живого каталога, правила ввоза —
// те же, что стоят в расчёте карточки (src/pricing.js).
//
// Почему не в `src/catalog-landings.js`: вопросы собираются на ходу, из количества машин
// раздела и типа двигателя, а не пишутся руками для каждой страницы. Сто десять
// одинаковых наборов и не нужны — половина ответов у разделов разного типа разная.
//
// Один и тот же набор показывают и приложение (блок под выдачей), и сервер (страница
// для поисковика вместе с разметкой FAQPage), поэтому файл лежит в общем коде.
//
// Про льготу на электромобиль здесь намеренно нет обещания «пошлины нет»: квота
// заканчивается, и такой ответ через месяц соврал бы. Формулировка «пока действует
// квота — нулевая ставка, после неё 15%» остаётся верной в обоих случаях.

const RU = new Intl.NumberFormat("ru-RU");
const number = (value) => RU.format(Math.round(Number(value) || 0));
const plural = (value, one, few, many) => {
  const abs = Math.abs(Math.round(Number(value) || 0)) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return many;
  if (last > 1 && last < 5) return few;
  return last === 1 ? one : many;
};

// Название раздела в родительном смысле «о чём эта страница». У марки в названии стоит
// только имя марки («BYD»), в вопросе оно само по себе звучало бы обрывком.
const subject = (landing) => {
  if (landing.kind === "brand") return `Автомобили ${landing.brand}`;
  if (landing.kind === "price") return landing.name.replace(/^Бензиновые /, "Бензиновые автомобили ");
  return landing.name;
};

// Тип двигателя раздела: у марки и кузова его нет — там в списке стоят машины всех типов.
