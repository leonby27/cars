// Имя модели в адресе каталожной страницы модели: `/catalog/byd/seal-06-dm-i`.
//
// Одно правило на сервер и приложение — иначе ссылка из карточки и адрес, который
// понимает сервер, разойдутся. Правило нарочно простое: строчные латинские буквы и
// цифры, всё остальное — дефис. «+» и «&» разворачиваются в слова, чтобы «P7» и
// «P7+» не склеились в один адрес (у XPeng это две разные машины).
//
// Файл без импортов: его читает справочник разделов каталога, а тот сам нужен
// многим модулям — любой импорт отсюда рисковал бы кольцом.
export const modelSlug = (model) =>
  String(model || "")
    .toLowerCase()
    .replace(/\+/g, " plus")
    .replace(/&/g, " and ")
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
