// Как сборщик обязан выглядеть для источника. Каждая проверка здесь — след от
// реальной поломки 31.08.2026: тогда обход упирался в стену на 51–113 страницах,
// а после снятия этих примет прочитал всю марку (208 страниц) без единой заминки.
// Смысл проверок не в красоте кода, а в том, чтобы примета не вернулась незаметно
// при следующей правке: подробности в памяти проекта, che168-working-list-walk.
import assert from "node:assert/strict";
import test from "node:test";
import { readFileSync } from "node:fs";

const source = readFileSync(new URL("../scripts/refresh-che168.mjs", import.meta.url), "utf8");
const importer = readFileSync(new URL("../scripts/import-v2.mjs", import.meta.url), "utf8");

test("сборщик не выдаёт себя за макбук", () => {
  // Главная примета: подпись «Macintosh» на линуксовом сервере противоречила всему
  // остальному в браузере (тип системы, шрифты, отрисовка). Ручные прогоны в том же
  // браузере без подмены проходили 199–211 страниц, наш скрипт с подменой — 107–113.
  for (const [name, text] of [["refresh-che168", source], ["import-v2", importer]]) {
    assert.doesNotMatch(text, /Macintosh/, `${name}: подпись браузера снова притворяется маком`);
  }
});

test("метка кэша постоянная, а не нумерованная", () => {
  // `_rsc=r1, r2, r3…` — это «не отдавай из кэша» сто раз подряд, подпись машины
  // прямо в адресе. У приложения сайта метка одна на весь раздел.
  assert.doesNotMatch(source, /_rsc=\$\{[^}]*(Seq|seq|\+\+|index|Index)/, "метка _rsc снова считается от запроса к запросу");
  assert.match(source, /const RSC_LIST\s*=/, "постоянная метка списков пропала");
  assert.match(source, /const RSC_DETAIL\s*=/, "постоянная метка карточек пропала");
});

test("неудачный запрос повторяется не больше двух раз", () => {
  // Четыре обращения к одному адресу подряд — долбёж, и рядом со стеной он ещё и
  // тратит запас впустую.
  const loop = source.match(/for \(let attempt = 0; attempt < (\d+); attempt \+= 1\)/);
  assert.ok(loop, "цикл повторов в запросе к источнику не найден");
  assert.ok(Number(loop[1]) <= 2, `повторов снова ${loop[1]}, а можно не больше двух`);
});

test("работаем в постоянном профиле браузера, а не в чистом окне", () => {
  assert.match(source, /launchPersistentContext/, "постоянный профиль заменили на чистое окно");
  assert.match(source, /PROFILE_DIR/, "каталог профиля пропал");
});

test("страница успевает отстояться перед первым запросом", () => {
  assert.match(source, /args\.get\("settle"\)/, "пауза «дать странице ожить» пропала");
});

test("чужой пропуск не подкладывается без явной просьбы", () => {
  // Метка, выданная другому браузеру, — чужой паспорт. Вход с сервера 31.08.2026
  // открыт и без неё.
  assert.match(source, /args\.get\("use-pass"\)/, "пропуск снова подкладывается всегда");
});

test("ходим по той версии сайта, на которой мерили", () => {
  // Оба успешных ручных замера шли через /ru/; на /en/ мы не проверяли.
  assert.match(source, /\/ru\/used-cars\?vehicle_list=1&\$\{params\}/, "запрос списков ушёл с русской версии");
  assert.doesNotMatch(source, /\/en\/used-cars\?vehicle_list=1&\$\{params\}/, "вернулась английская версия списков");
});

test("страницу каждой марки по умолчанию не открываем", () => {
  // Правка «вставать на страницу марки» стоила 113 обращений на марку и не дала
  // ничего: 113 прочитанных страниц против 107 без неё.
  assert.match(source, /args\.get\("stand-on-brand"\) === "true"/, "открывание страницы марки снова включено по умолчанию");
});

test("проверка популярных машин идёт после обхода списков", () => {
  assert.match(source, /args\.get\("priority-first"\) === "true"/, "проверка популярных снова идёт первой и съедает запас");
});

test("один поток и неспешная пауза", () => {
  const conc = source.match(/args\.get\("concurrency"\) \|\| (\d+)/);
  const pace = source.match(/args\.get\("pace"\) \|\| (\d+)/);
  assert.ok(conc && Number(conc[1]) === 1, "потоков снова больше одного");
  assert.ok(pace && Number(pace[1]) >= 1000, "пауза между обращениями стала меньше секунды");
});

test("не долбим закрытую дверь: две попытки входа и тишина на часы", () => {
  // 31.08.2026 мы стучались весь день — пять попыток, перезапуск, снова пять.
  // Каждый стук продлевал запрет, часть блокировок мы устроили себе сами.
  const waits = source.match(/: \[60_000, ([\d_]+)\];/);
  assert.ok(waits, "список пауз перед повторным входом не найден");
  const list = source.match(/const ENTRY_WAITS_MS[\s\S]{0,400}?\];/)[0];
  const count = (list.match(/\d+_000/g) || []).length;
  assert.ok(count <= 2, `попыток входа снова ${count + 1}, а можно не больше трёх`);
  assert.match(source, /LOCKOUT_HOURS/, "правило тишины после отказа пропало");
  assert.match(source, /underLockout/, "проверка запрета перед входом пропала");
});

test("новые машины показываются сразу: кэш страниц сбрасывается из прогона", () => {
  assert.match(source, /async function purgePageCache/, "сброс кэша страниц пропал из прогона");
  assert.match(source, /await purgePageCache\(added\)/, "сброс кэша больше не вызывается после заведения машин");
});
