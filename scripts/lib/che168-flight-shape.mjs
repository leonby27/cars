// Как отличить «источник ответил, машин в ответе нет» от «источник молчит».
//
// Приложение источника отдаёт данные потоком служебных строк вида `3:I[...]`.
// Так выглядит и карточка живой машины, и пустая страница снятого объявления
// (12 КБ против 88 КБ у живой), и страница за последней страницей списка.
// Заглушка проверки «не робот», обрыв связи и пустой ответ выглядят иначе.
//
// Цена ошибки: с начала сентября 2026 источник стал отдавать снятую машину такой
// пустой страницей вместо ошибки. Сборщик считал это молчанием, тридцать подряд
// — и предохранитель объявлял стену там, где её не было: четыре прогона подряд
// 05–06.09.2026 останавливались, пройдя 3–6 марок из 44 (см. память проекта).

// Строкой, а не готовым выражением: то же условие выполняется внутри страницы
// браузера, куда объект передать нельзя — только простые значения.
export const FLIGHT_SHAPE = String.raw`(^|\n)\d+:[I\[{"]`;

// Ниже этого размера ответ на настоящую страницу не бывает: пустая страница
// снятого объявления — около 12 КБ.
export const FLIGHT_MIN_LENGTH = 2000;

export function looksLikeFlight(text) {
  if (typeof text !== "string" || text.length <= FLIGHT_MIN_LENGTH) return false;
  return new RegExp(FLIGHT_SHAPE).test(text);
}
