-- Память «с этого адреса недавно открывали сайт» для защиты счётчика от подделок.
--
-- До этого она жила только в памяти процесса, и первые полчаса после каждого
-- перезапуска проверка пропускала всех подряд: накрутчик карточек попадал в
-- статистику ровно в эти окна (98 перезапусков за две недели, в том числе ночная
-- пересборка курсов — как раз когда он ходит). Теперь адреса сбрасываются сюда
-- каждые несколько секунд и при остановке, а при старте поднимаются обратно.
-- Строки старше получаса не нужны и подчищаются при каждом сбросе.
CREATE TABLE IF NOT EXISTS site_requests (
  address TEXT PRIMARY KEY,
  seen_at TIMESTAMPTZ NOT NULL
);
