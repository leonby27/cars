-- Недельный снимок цен: одна строка на «марка + модель + год выпуска».
--
-- Зачем: отчёт «что подешевело за неделю» по сегодняшней базе посчитать нельзя —
-- вчерашних цен в ней нет. История цены есть только у объявления (previous_price_usd),
-- но объявления уходят с продажи, и по ним рынок не измерить: пропала дорогая машина —
-- средняя упала, хотя ничего не подешевело.
--
-- Поэтому снимок по «корзине»: цена считается по одинаковым наборам «модель+год»
-- неделю к неделе, и в расчёт идут только те наборы, что были в обоих снимках.
-- Иначе рост самого каталога (то +47 бензиновых марок, то −8 406 машин) читался бы
-- как движение рынка.
--
-- Медиана, а не среднее: одна машина за 95 000 в наборе из десяти сдвигает среднее,
-- а медиану — нет.
CREATE TABLE IF NOT EXISTS price_snapshots (
  taken_on DATE NOT NULL,
  bucket TEXT NOT NULL,
  brand TEXT NOT NULL,
  model TEXT NOT NULL,
  model_year INT,
  listings INT NOT NULL,
  median_usd NUMERIC(10,2) NOT NULL,
  min_usd NUMERIC(10,2) NOT NULL,
  PRIMARY KEY (taken_on, bucket)
);

-- Чтение всегда идёт по набору за две даты: «этот же набор неделю назад».
CREATE INDEX IF NOT EXISTS price_snapshots_bucket_idx ON price_snapshots (bucket, taken_on);
