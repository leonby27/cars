-- Отдельная отметка: посетитель не просто пробыл на странице, а что-то сделал —
-- подвигал мышью, коснулся экрана, прокрутил, нажал клавишу. Понадобилась после
-- 26.08.2026: обходчик, который ходит через домашние адреса живых людей и потому
-- неотличим по адресу, брал страницу, ровно 15 секунд ждал и уходил — то есть
-- получал отметку «живой» по одному лишь времени на странице. Время само по себе
-- больше не делает посетителя человеком: в разделе аналитики считаются только те,
-- за кем есть действие, остальные заходы видны отдельной цифрой.
ALTER TABLE analytics_events ADD COLUMN IF NOT EXISTS human_action BOOLEAN NOT NULL DEFAULT false;
CREATE INDEX IF NOT EXISTS analytics_events_human_action_idx
  ON analytics_events(visitor_id, created_at DESC)
  WHERE human_action;

-- Прошлые записи переносим как есть: за какое действие им когда-то поставили «живой»,
-- уже не восстановить, а обнулять историю раздела из-за смены правила незачем.
UPDATE analytics_events SET human_action = true WHERE human AND NOT human_action;
