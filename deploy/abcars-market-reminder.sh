#!/bin/bash
# Напоминание обновить сравнение цен с белорусским рынком — раз в квартал в телеграм.
#
# Почему напоминание, а не автоматический сбор: площадка av.by блокирует адреса
# дата-центров, с сервера её страницы не открываются вовсе. Сбор идёт только с
# домашней сети, командой `npm run market` на компьютере Сергея. Сервер умеет
# единственное — вовремя напомнить.
#
# Почему отдельный скрипт, а не запуск кода из репозитория: тогда напоминание
# зависело бы от того, выложена ли на сервер свежая версия сайта. Здесь нужны
# только токен бота из настроек и адрес чата — и то и другое на сервере уже есть.
set -euo pipefail

# Первое напоминание — 1 января 2027 года. Октябрьское пропускаем: свод цен собран
# в сентябре 2026-го, и напоминать об обновлении через две недели после сбора незачем.
# Дальше всё идёт своим чередом — январь, апрель, июль, октябрь. Чтобы вернуть
# пропущенное напоминание, достаточно стереть эти три строки.
SKIP_UNTIL=2026-12-01
if [[ "$(date -u +%Y-%m-%d)" < "$SKIP_UNTIL" ]]; then
  echo "напоминание пропущено: цены собраны недавно, первое придёт после $SKIP_UNTIL"
  exit 0
fi

ENV_FILE=/srv/abcars/.env.local
CHAT_FILE=/srv/abcars/runtime/telegram-chat.json

[ -r "$ENV_FILE" ] || { echo "нет $ENV_FILE — напоминание не отправлено"; exit 0; }
set -a; source "$ENV_FILE"; set +a

TOKEN="${TELEGRAM_BOT_TOKEN:-}"
[ -n "$TOKEN" ] || { echo "TELEGRAM_BOT_TOKEN не задан — напоминание не отправлено"; exit 0; }

# Адрес чата: из настроек, а если его там нет — из файла, который бот запомнил сам
# после первого же сообщения человека (см. scripts/night-watch.mjs).
CHAT_ID="${TELEGRAM_CHAT_ID:-}"
if [ -z "$CHAT_ID" ] && [ -r "$CHAT_FILE" ]; then
  CHAT_ID=$(sed -n 's/.*"chatId"[[:space:]]*:[[:space:]]*"\{0,1\}\([-0-9]\{1,\}\).*/\1/p' "$CHAT_FILE" | head -1)
fi
[ -n "$CHAT_ID" ] || { echo "адрес чата неизвестен — напишите боту любое сообщение"; exit 0; }

TEXT=$'Пора обновить сравнение цен с белорусским рынком.\n\nСкажите Claude: «обнови сравнение цен» — или запустите сами:\ncd ~/Documents/Files/profile2/AI-Folders/car/chinacar-mvp && npm run market\n\nСбор идёт с домашнего компьютера (с сервера площадка недоступна) и занимает около получаса. После сбора нужна обычная выкладка сайта, чтобы новые цифры попали на страницу /price-belarus.'

curl -sS -m 30 -X POST "https://api.telegram.org/bot${TOKEN}/sendMessage" \
  --data-urlencode "chat_id=${CHAT_ID}" \
  --data-urlencode "text=${TEXT}" \
  --data-urlencode "disable_web_page_preview=true" >/dev/null

echo "напоминание про сравнение цен отправлено"
